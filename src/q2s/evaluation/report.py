ROOT = Path(__file__).resolve().parents[3]
REPORTS = ROOT / "reports"

STACK_LABEL = {
    "today": "Today's process",
    "system": "The system",
    "system, FIFO release": "System, first-come release",
    "system, ATCS release": "System, ATCS release",
    "system, today's quotes": "System, today's quotes",
    "system, buy per order": "System, parts per order",
}


def _mean(rows: list[dict[str, Any]], stack: str, metric: str) -> float:
    vals = [r[metric] for r in rows if r["stack"] == stack]
    return float(np.mean(vals)) if vals else float("nan")


def _money(x: float) -> str:
    return f"${x:,.0f}"


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _ci(c: dict[str, float], money: bool = False, pct: bool = False) -> str:
    if money:
        return f"{c['mean']:+,.0f} $ ({c['low']:+,.0f} to {c['high']:+,.0f})"
    if pct:
        return f"{100 * c['mean']:+.1f} pts ({100 * c['low']:+.1f} to {100 * c['high']:+.1f})"
    return f"{c['mean']:+.2f} ({c['low']:+.2f} to {c['high']:+.2f})"


def summary(res: dict[str, Any]) -> dict[str, Any]:
    rows = res["rows"]
    stacks = [s for s in res["stacks"] if any(r["stack"] == s for r in rows)]
    metrics = [
        "contribution_per_day",
        "revenue",
        "win_rate",
        "on_time",
        "late_days_mean",
        "lead_days_median",
        "lead_days_p90",
        "promise_days_median",
        "parts_wait_days_mean",
        "late_credits",
        "holding",
        "boards_per_day",
    ]
    table = {s: {m: _mean(rows, s, m) for m in metrics} for s in stacks}
    sys_rows = [r for r in rows if r["stack"] == "system" and r.get("forecasts")]
    fc = sys_rows[0]["forecasts"] if sys_rows else {}
    return {"table": table, "forecasts": fc}


def first_runs(res: dict[str, Any], reports: Path) -> dict[str, dict[str, Any]]:
    """The pinned first run of each held-out set; the latest run only if none was recorded."""
    out = {}
    for set_name, v in (res.get("scenarios_heldout") or {}).items():
        first = reports / "heldout" / set_name / "first_run.json"
        out[set_name] = json.loads(first.read_text())["results"] if first.exists() else v["latest"]
    return out


def build(reports: Path = REPORTS) -> None:
    res = json.loads((reports / "results.json").read_text())
    s = summary(res)
    s["heldout_first"] = first_runs(res, reports)
    sv = reports / "solvers.json"
    s["solvers"] = json.loads(sv.read_text()) if sv.exists() else None
    (reports / "REPORT.md").write_text(markdown(res, s))
    (reports / "dashboard.html").write_text(dashboard(res, s))


