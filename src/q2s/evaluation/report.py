def _bars(items: list[tuple[str, float]], fmt, width: int = 470, height_per: int = 34) -> str:
    """A horizontal bar chart as inline SVG (negative values extend left of zero)."""
    if not items:
        return '<p class="empty">Nothing to show yet: run <code>q2s evaluate</code>.</p>'
    vals = [v for _, v in items]
    lo, hi = min(0.0, min(vals)), max(0.0, max(vals))
    span = (hi - lo) or 1.0
    label_w, pad = 180, 112
    plot_w = width - label_w - pad
    zero = label_w + (0 - lo) / span * plot_w
    h = height_per * len(items) + 8
    rows = []
    for i, (label, v) in enumerate(items):
        y = 4 + i * height_per
        x0, x1 = sorted([zero, label_w + (v - lo) / span * plot_w])
        cls = "bar neg" if v < 0 else "bar"
        tx = x1 + 6 if v >= 0 else x0 - 6
        anchor = "start" if v >= 0 else "end"
        rows.append(
            f'<text x="{label_w - 12}" y="{y + 20}" class="lbl" text-anchor="end">{html.escape(label)}</text>'
            f'<rect x="{x0:.1f}" y="{y + 6}" width="{max(x1 - x0, 1.5):.1f}" height="20" rx="2" class="{cls}"/>'
            f'<text x="{tx:.1f}" y="{y + 20}" class="val" text-anchor="{anchor}">{html.escape(fmt(v))}</text>'
        )
    return (
        f'<svg viewBox="0 0 {width} {h}" role="img" class="chart">'
        f'<line x1="{zero:.1f}" x2="{zero:.1f}" y1="0" y2="{h}" class="axis"/>{"".join(rows)}</svg>'
    )


def _pairs(items: list[tuple[str, float, float]], fmt, width: int = 470, height_per: int = 30) -> str:
    """Truth (filled) against twin (ring) per option, on one axis."""
    if not items:
        return '<p class="empty">The machine study has not run yet.</p>'
    vals = [v for _, a, b in items for v in (a, b)]
    lo, hi = min(0.0, min(vals)), max(vals) or 1.0
    span = (hi - lo) or 1.0
    label_w, pad = 150, 24
    plot_w = width - label_w - pad
    h = height_per * len(items) + 30
    zero = label_w + (0 - lo) / span * plot_w
    out = [f'<line x1="{zero:.1f}" x2="{zero:.1f}" y1="0" y2="{h - 24}" class="axis"/>']
    for i, (label, truth, twin) in enumerate(items):
        y = 14 + i * height_per
        xt = label_w + (truth - lo) / span * plot_w
        xw = label_w + (twin - lo) / span * plot_w
        out.append(
            f'<text x="{label_w - 12}" y="{y + 5}" class="lbl" text-anchor="end">{html.escape(label)}</text>'
            f'<line x1="{min(xt, xw):.1f}" x2="{max(xt, xw):.1f}" y1="{y}" y2="{y}" class="link"/>'
            f'<circle cx="{xt:.1f}" cy="{y}" r="6" class="truth"><title>truth {fmt(truth)}</title></circle>'
            f'<circle cx="{xw:.1f}" cy="{y}" r="6" class="twin"><title>twin {fmt(twin)}</title></circle>'
        )
    out.append(f'<text x="{label_w}" y="{h - 6}" class="note">● truth  ○ twin, late credits saved in the month</text>')
    return f'<svg viewBox="0 0 {width} {h}" role="img" class="chart">{"".join(out)}</svg>'


