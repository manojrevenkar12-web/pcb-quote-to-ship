def markdown(res: dict[str, Any], s: dict[str, Any]) -> str:
    t = s["table"]
    c = res["comparisons"].get("system", {})
    out = ["# Results", "", "_Generated by `q2s report` from `reports/results.json`. Do not edit by hand._", ""]
    out += [
        f"Seeds: {', '.join(map(str, res['seeds']))}. Each run: 60 days of history under today's process, "
        "35 test days (the first 10 absorb the backlog and are not scored), 8 days to let orders finish. "
        "Every stack sees the same requests, failures, supplier delays and customer draws.",
        "",
    ]
    out += [
        "## Stacks, mean over seeds",
        "",
        "| | Contribution / day | Win rate | On time | Late days / order | Lead p90 | Promise (median) "
        "| Parts wait | Late credits | Holding |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for st, m in t.items():
        out.append(
            f"| {STACK_LABEL.get(st, st)} | {_money(m['contribution_per_day'])} | {_pct(m['win_rate'])} | "
            f"{_pct(m['on_time'])} | {m['late_days_mean']:.2f} | {m['lead_days_p90']:.1f} d | "
            f"{m['promise_days_median']:.1f} d | {m['parts_wait_days_mean']:.2f} d | "
            f"{_money(m['late_credits'])} | {_money(m['holding'])} |"
        )
    if c:
        out += [
            "",
            "## The system against today's process (paired by seed, 90% bootstrap interval)",
            "",
            f"- Contribution per day: {_ci(c['contribution_per_day'], money=True)}",
            f"- On time: {_ci(c['on_time'], pct=True)}",
            f"- Late days per order: {_ci(c['late_days_mean'])}",
            f"- Win rate: {_ci(c['win_rate'], pct=True)}",
            f"- Lead time p90 (days): {_ci(c['lead_days_p90'])}",
        ]
    abl = {k: v for k, v in res["comparisons"].items() if k.startswith("system vs ")}
    if abl:
        out += [
            "",
            "## What each part is worth (the full system minus the system with that part switched back)",
            "",
            "| Switched back | Contribution / day | On time |",
            "|---|---:|---:|",
        ]
        for k, v in abl.items():
            out.append(
                f"| {STACK_LABEL.get(k[10:], k[10:])} | {_ci(v['contribution_per_day'], money=True)} | "
                f"{_ci(v['on_time'], pct=True)} |"
            )
    fc = s["forecasts"]
    if fc:
        out += [
            "",
            "## How far the outlook can be trusted (first seed)",
            "",
            "| Days ahead | Panels finished: error (MAPE) | Bias | Twin's own 80% band covers | "
            "Conformal 80% band covers |",
            "|---:|---:|---:|---:|---:|",
        ]
        conf = fc.get("panels_conformal", {})
        for h, v in fc["panels"].items():
            cv = conf.get(str(h), conf.get(h))
            out.append(
                f"| {h} | {_pct(v['mape'])} | {v['bias']:+.1%} | {_pct(v['coverage_p10_p90'])} | "
                f"{_pct(cv) if cv is not None else 'n/a'} |"
            )
        sd = fc.get("ship_day", {})
        if sd:
            out += [
                "",
                f"Ship day of every order in progress, predicted each morning: within one day "
                f"{_pct(sd['within_1_day'])} of the time; the predicted p90 day covers "
                f"{_pct(sd['p90_covers'])} ({sd['n']:,} predictions).",
            ]
    solver = [r["solver"] for r in res["rows"] if r["stack"] == "system" and r.get("solver")]
    if solver:
        tot = {k: sum(x[k] for x in solver) for k in ("optimal", "feasible", "fallback")}
        out += [
            "",
            "## The release solver each morning (the system, all seeds)",
            "",
            f"CP-SAT proved the optimum on {tot['optimal']} mornings, returned a feasible plan inside the "
            f"time limit on {tot['feasible']}, and fell back to ATCS on {tot['fallback']}.",
        ]
    sv = s.get("solvers")
    if sv:
        names = list(next(iter(sv["sizes"].values())).keys())
        out += [
            "",
            "## Two models of the release problem, by size",
            "",
            "CP-SAT (`schedule.solve_cpsat`) against an independently written MiniZinc model "
            f"(`models/release.mzn`) on {sv['per_size']} random mornings per size, "
            f"{sv['seconds_limit']:.0f} s each. Cells: proven optimal, median seconds to prove; "
            "agreement counts proven optima equal to CP-SAT's proven optimum.",
            "",
            "| Orders | " + " | ".join(names) + " |",
            "|---:|" + "---:|" * len(names),
        ]
        for n, row in sv["sizes"].items():
            cells = []
            for name in names:
                c = row[name]
                med = f"{c['median_seconds']:.1f} s" if c["median_seconds"] is not None else "–"
                agree = f", {c['agree_with_cpsat']}/{c['compared']} agree" if name != "cp-sat" and c["compared"] else ""
                early = c["ended_without_solution_early"]
                bad = f", **{early} ended early with no solution**" if early else ""
                if c.get("errors"):
                    bad += f", {c['errors']} could not load the instance"
                cells.append(f"{c['proven']}/{sv['per_size']}, {med}{agree}{bad}")
            out.append(f"| {n} | " + " | ".join(cells) + " |")
    m = res.get("machines")
    if m:
        out += [
            "",
            "## What is the next machine worth? Twin against truth",
            "",
            f"Same month replayed with one more resource. Late credits saved over the month; truth from the "
            f"simulated factory, prediction from the twin calibrated on the 60 days before. "
            f"Rank correlation {m['rank_correlation']:+.2f}; truth's best: {m['truth_best']}, "
            f"twin's best: {m['twin_best']}.",
            "",
            "| Option | Truth: credits saved | Twin: credits saved | Truth: flow days | Twin: flow days |",
            "|---|---:|---:|---:|---:|",
        ]
        for name, row in m["options"].items():
            if name == "none":
                continue
            out.append(
                f"| {name} | {_money(row['truth_saving'])} | {_money(row['twin_saving'])} | "
                f"{row['truth_flow_change']:+.2f} | {row['twin_flow_change']:+.2f} |"
            )
    for key, title in (("scenarios_dev", "Development scenarios"),):
        sc = res.get(key)
        if sc:
            out += [
                "",
                f"## {title}",
                "",
                "| Scenario | Contribution / day: today → system | On time: today → system |",
                "|---|---:|---:|",
            ]
            for name, v in sc.items():
                out.append(
                    f"| {name} | {_money(v['today']['contribution_per_day'])} → "
                    f"{_money(v['system']['contribution_per_day'])} | {_pct(v['today']['on_time'])} → "
                    f"{_pct(v['system']['on_time'])} |"
                )
    ho = res.get("scenarios_heldout")
    if ho:
        for set_name, v in ho.items():
            fr = s["heldout_first"][set_name]
            out += [
                "",
                f"## Held-out scenarios `{set_name}` (written blind; first run, status: {v['status']})",
                "",
                "| Scenario | Contribution / day: today → system | On time: today → system | "
                "Late days / order: today → system |",
                "|---|---:|---:|---:|",
            ]
            for name, r in fr.items():
                out.append(
                    f"| {name} | {_money(r['today']['contribution_per_day'])} → "
                    f"{_money(r['system']['contribution_per_day'])} | {_pct(r['today']['on_time'])} → "
                    f"{_pct(r['system']['on_time'])} | {r['today']['late_days_mean']:.2f} → "
                    f"{r['system']['late_days_mean']:.2f} |"
                )
    out += ["", f"Run time: {res.get('seconds', 0) / 60:.0f} minutes on two CPU cores.", ""]
    return "\n".join(out)


